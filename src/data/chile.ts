export const REGION_BY_CODE = new Map(REGIONS.map((r) => [r.code, r]));

export function getRegion(code: string): Region | undefined {
  return REGION_BY_CODE.get(code);
}

export function isValidRegionCommune(regionCode: string, commune: string): boolean {
  const region = REGION_BY_CODE.get(regionCode);
  if (!region) return false;
  return region.communes.includes(commune);
}
